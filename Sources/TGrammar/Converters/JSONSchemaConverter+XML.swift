// Parameter-list styles: the root object is a sequence of tagged parameters whose string values
// are raw text and whose other values are JSON. Qwen, MiniMax, ATEM, GLM and Kimi K3 differ only in
// their wrapper strings and key attributes; DeepSeek adds a `string` attribute correlated with
// the value's type.
extension JSONSchemaConverter {
    struct XMLWrapper {
        let keyPrefix: String
        let keySuffix: String
        let valuePrefix: String
        let parameterSuffix: String
    }

    var xmlWrapper: XMLWrapper {
        switch style {
        case .qwenXML: .init(keyPrefix: "<parameter=", keySuffix: ">", valuePrefix: "", parameterSuffix: "</parameter>")
        case .miniMaxXML: .init(keyPrefix: "<parameter name=\"", keySuffix: "\">", valuePrefix: "", parameterSuffix: "</parameter>")
        case .atemXML: .init(keyPrefix: "<atem:parameter name=\"", keySuffix: "\">", valuePrefix: "", parameterSuffix: "</atem:parameter>")
        case .deepSeekXML: .init(keyPrefix: "<｜DSML｜parameter name=\"", keySuffix: "", valuePrefix: "", parameterSuffix: "</｜DSML｜parameter>")
        case .deepSeekV41XML: .init(keyPrefix: "<｜DSML｜ parameter name=\"", keySuffix: "", valuePrefix: "", parameterSuffix: "</｜DSML｜ parameter>")
        case .glmXML: .init(keyPrefix: "<arg_key>", keySuffix: "</arg_key>", valuePrefix: "<arg_value>", parameterSuffix: "</arg_value>")
        case .cohereXML: .init(keyPrefix: "<cofl:value", keySuffix: ">", valuePrefix: "", parameterSuffix: "</cofl:value>")
        // The key suffix (type attribute and separator) is generated by `xmlKeySuffix`.
        case .kimiK3XML: .init(keyPrefix: "<|open|>argument key=\"", keySuffix: "", valuePrefix: "", parameterSuffix: "<|close|>argument<|sep|>")
        case .json, .gemma, .functionGemma, .pythonic, .miniMaxM3XML: .init(keyPrefix: "", keySuffix: "", valuePrefix: "", parameterSuffix: "")
        }
    }

    var isDeepSeek: Bool { style == .deepSeekXML || style == .deepSeekV41XML }

    /// Unrestricted raw text up to the parameter's closing tag; the enclosing property rule
    /// matches the tag itself, outside this body's exclusion scope.
    func xmlString() throws(GrammarError) -> Int32 {
        try sharedRule(.xmlString) { () throws(GrammarError) in
            builder.addTagDispatch(.init(loopAfterDispatch: false, excludes: (options.excludes + [xmlWrapper.parameterSuffix]).map { Array($0.utf8) }))
        }
    }

    /// An identifier key for additional parameters.
    func xmlVariableName() throws(GrammarError) -> Int32 {
        try sharedRule(.xmlVariableName) { () throws(GrammarError) in
            if !options.excludes.isEmpty { return try excludingString("[a-zA-Z_][a-zA-Z0-9_]*", hint: "xml_variable_name") }
            return sequence([builder.addCharacterClass([97 ... 122, 65 ... 90, 95 ... 95]),
                             builder.addCharacterClassStar([97 ... 122, 65 ... 90, 48 ... 57, 95 ... 95])])
        }
    }

    /// The unconstrained parameter list: any identifier keys with any values.
    func xmlObject() throws(GrammarError) -> Int32 {
        try sharedRule(.xmlObject) { () throws(GrammarError) in
            let saved = level
            level = 0
            defer { level = saved }
            return try object(.object([.init(key: "type", value: .string("object")), .init(key: "additionalProperties", value: .bool(true))]), depth: 0, hint: "xml_object")
        }
    }

    /// Any parameter value: raw text already covers numbers, booleans and null.
    func xmlAny() throws(GrammarError) -> Int32 {
        try sharedRule(.xmlAny) { () throws(GrammarError) in
            let saved = level
            level = 1
            defer { level = saved }
            return choice([ref(try xmlString()), ref(try rule(Self.anyValueSchemas[4], depth: 1, hint: "json_array")),
                           ref(try rule(Self.anyValueSchemas[5], depth: 1, hint: "json_object"))])
        }
    }

    /// A raw parameter value for a string schema.
    func rawParameterString(_ schema: JSONValue, hint: String) throws(GrammarError) -> Int32 {
        if let pattern = try rawPatternExpression(schema) { return pattern }
        let bounds = try stringBounds(schema)
        // Without exclusions, a length bound or an unrecognised format keeps a plain repetition.
        // With exclusions the raw string keeps only the exclusions: length bounds are dropped.
        if options.excludes.isEmpty, bounds.isBounded || schema["format"] != nil {
            return repeatExpr(anyCharacter(), min: bounds.min, max: bounds.max, hint: hint + "_characters")
        }
        return ref(try xmlString())
    }

    /// Kimi K3 escapes attribute values; the other styles spell keys as written.
    func xmlAttributeValue(_ key: String) -> String {
        guard style == .kimiK3XML else { return key }
        return key.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "\"", with: "&quot;")
    }

    static let kimiK3Types = ["string", "number", "integer", "boolean", "object", "array", "null"]

    /// What follows the key. A declared Kimi K3 property carries exactly the type its value is
    /// rendered with; free-form keys keep the whole set.
    func xmlKeySuffix(pinnedType: String?) -> Int32 {
        guard style == .kimiK3XML else { return literal(xmlWrapper.keySuffix) }
        let type = pinnedType.map { literal($0) } ?? choice(Self.kimiK3Types.map { literal($0) })
        return sequence([literal("\" type=\""), type, literal("\"<|sep|>")])
    }

    /// `xml_string` already accepts whitespace; padding it again would create one Earley state
    /// per possible split of the string body.
    func xmlValue(_ value: Int32) -> Int32 {
        value == shared[.xmlString] ? ref(value) : sequence([whitespace(), ref(value), whitespace()])
    }

    func xmlParameter(key: String, value: Int32, schema: JSONValue, hint: String) throws(GrammarError) -> Int32 {
        if isDeepSeek {
            guard allowedText(key) else { return unsatisfiable() }
            return sequence([literal(xmlWrapper.keyPrefix + key), try deepSeekParameterSuffix(schema, value: value, hint: hint)])
        }
        let escaped = xmlAttributeValue(key)
        guard allowedText(escaped) else { return unsatisfiable() }
        let keyExpr = sequence([literal(xmlWrapper.keyPrefix + escaped), xmlKeySuffix(pinnedType: style == .kimiK3XML ? renderedType(schema) : nil)])
        return xmlParameterTail(keyExpr: keyExpr, value: value)
    }

    func xmlParameter(keyExpr: Int32, value: Int32, schema: JSONValue, hint: String) throws(GrammarError) -> Int32 {
        if isDeepSeek {
            return sequence([literal(xmlWrapper.keyPrefix), keyExpr, try deepSeekParameterSuffix(schema, value: value, hint: hint)])
        }
        let key = sequence([literal(xmlWrapper.keyPrefix), keyExpr, xmlKeySuffix(pinnedType: style == .kimiK3XML ? renderedType(schema) : nil)])
        return xmlParameterTail(keyExpr: key, value: value)
    }

    private func xmlParameterTail(keyExpr: Int32, value: Int32) -> Int32 {
        var elements = [keyExpr]
        if !xmlWrapper.valuePrefix.isEmpty { elements += [whitespace(), literal(xmlWrapper.valuePrefix)] }
        elements += [xmlValue(value), literal(xmlWrapper.parameterSuffix)]
        return sequence(elements)
    }

    // MARK: DeepSeek

    /// `string="true"` wraps a raw string whose whitespace is part of the value; `string="false"`
    /// wraps a JSON value that may be padded. Unions and mixed enums produce one alternative per
    /// option. `value` is the caller's rule for `schema`, or `nil` to build it when a typed leaf
    /// is reached, so a nested union is not rebuilt at every level.
    func deepSeekParameterSuffix(_ schema: JSONValue?, value: Int32?, hint: String) throws(GrammarError) -> Int32 {
        if let pointer = schema?["$ref"]?.string {
            if let cached = referenceSuffixRules[pointer] { return ref(cached) }
            // Register before resolving: a recursive branch refers back to this rule, and shared
            // acyclic subgraphs are built once.
            let id = builder.addEmptyRule(hint: hint + "_dsml_param")
            referenceSuffixRules[pointer] = id
            builder.updateRuleBody(id, try deepSeekParameterSuffix(resolve(pointer), value: value, hint: hint))
            return ref(id)
        }
        func wrap(_ valueExpr: Int32, isString: Bool) -> Int32 {
            var elements = [literal(isString ? "\" string=\"true\">" : "\" string=\"false\">")]
            if !isString { elements.append(whitespace()) }
            elements.append(valueExpr)
            if !isString { elements.append(whitespace()) }
            elements.append(literal(xmlWrapper.parameterSuffix))
            return sequence(elements)
        }
        if let pinned = renderedType(schema) {
            let valueRule = if let value { value } else { try rule(schema!, depth: 1, hint: hint) }
            return wrap(ref(valueRule), isString: pinned == "string")
        }
        guard let options = try compositeOptions(schema, splitEnums: true) else {
            // No schema, {} and allOf with several schemas all render any value.
            let json = try ["number", "boolean", "null"].map { type throws(GrammarError) in ref(try rule(Self.typeSchema(type), depth: 1, hint: "json_\(type)")) }
                + [ref(try rule(Self.anyValueSchemas[4], depth: 1, hint: "json_array")), ref(try rule(Self.anyValueSchemas[5], depth: 1, hint: "json_object"))]
            return choice([wrap(ref(try xmlString()), isString: true), wrap(choice(json), isString: false)])
        }
        return choice(try options.enumerated().map { index, option throws(GrammarError) in
            try deepSeekParameterSuffix(option, value: nil, hint: hint + "_dsml_case_\(index)")
        })
    }
}
